import AppKit
import Combine
import CryptoKit

struct ClipItem: Codable, Identifiable, Equatable {
    var id = UUID()
    var text: String                 // plain text (for images: "Image 1280×720")
    var date = Date()
    var favorite = false
    var imageFile: String?           // PNG stored in the images folder
    var rtf: Data?                   // original formatting, if any
    var html: Data?

    var isImage: Bool { imageFile != nil }
    var hasFormat: Bool { rtf != nil || html != nil }
}

/// Keeps the clipboard history and watches the system pasteboard for changes.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published var autoPaste: Bool {
        didSet { defaults.set(autoPaste, forKey: "autoPaste") }
    }
    @Published var showPreview: Bool {
        didSet { defaults.set(showPreview, forKey: "showPreview") }
    }

    let maxHistory: Int
    static let maxImageBytes = 25_000_000
    static let maxFormatBytes = 300_000

    private let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private var timer: Timer?
    private var lastChangeCount: Int
    private let fileURL: URL
    let imagesDir: URL
    private let thumbCache = NSCache<NSString, NSImage>()

    /// Markers used by password managers and other apps to flag sensitive or temporary data. Never stored.
    /// See http://nspasteboard.org
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    static var defaultDirectory: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("PasteShelf", isDirectory: true)
    }

    init(directory: URL = ClipboardStore.defaultDirectory,
         pasteboard: NSPasteboard = .general,
         defaults: UserDefaults = .standard,
         maxHistory: Int = 100) {
        self.pasteboard = pasteboard
        self.defaults = defaults
        self.maxHistory = maxHistory
        lastChangeCount = pasteboard.changeCount
        imagesDir = directory.appendingPathComponent("images", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        fileURL = directory.appendingPathComponent("history.json")
        autoPaste = defaults.object(forKey: "autoPaste") as? Bool ?? true
        showPreview = defaults.object(forKey: "showPreview") as? Bool ?? true
        load()
    }

    var favorites: [ClipItem] { items.filter(\.favorite) }
    var history: [ClipItem] { items.filter { !$0.favorite } }

    /// Favorites and history filtered by the search text, in display order.
    func visible(search: String) -> (favs: [ClipItem], hist: [ClipItem]) {
        let match: (ClipItem) -> Bool = { search.isEmpty || $0.text.localizedCaseInsensitiveContains(search) }
        return (favorites.filter(match), history.filter(match))
    }

    // MARK: - Watching the pasteboard

    func startMonitoring() {
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.checkPasteboard() }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Reads the pasteboard only when its change count moved, so idle polling never touches the contents.
    func checkPasteboard() {
        let pb = pasteboard
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        let rtf = pb.data(forType: .rtf).flatMap { $0.count <= Self.maxFormatBytes ? $0 : nil }
        let html = pb.data(forType: .html).flatMap { $0.count <= Self.maxFormatBytes ? $0 : nil }
        // Text first: copying files in Finder also puts the file icon on the pasteboard, which we don't want.
        let text = pb.string(forType: .string)
            ?? rtf.flatMap { NSAttributedString(rtf: $0, documentAttributes: nil)?.string }
            ?? html.flatMap { NSAttributedString(html: $0, documentAttributes: nil)?.string }
        if let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            addText(text, rtf: rtf, html: html)
        } else if let (png, size) = imagePNG(from: pb) {
            addImage(png, size: size)
        }
    }

    private func imagePNG(from pb: NSPasteboard) -> (Data, NSSize)? {
        let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff)
        guard let raw, raw.count <= Self.maxImageBytes, let rep = NSBitmapImageRep(data: raw) else { return nil }
        let png = pb.data(forType: .png) ?? rep.representation(using: .png, properties: [:])
        guard let png else { return nil }
        return (png, NSSize(width: rep.pixelsWide, height: rep.pixelsHigh))
    }

    func addText(_ text: String, rtf: Data? = nil, html: Data? = nil) {
        if let idx = items.firstIndex(where: { !$0.isImage && $0.text == text }) {
            var existing = items.remove(at: idx)
            existing.date = Date()
            if rtf != nil || html != nil { existing.rtf = rtf; existing.html = html }
            items.insert(existing, at: 0)
        } else {
            items.insert(ClipItem(text: text, rtf: rtf, html: html), at: 0)
        }
        trimAndSave()
    }

    func addImage(_ png: Data, size: NSSize) {
        let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        let name = String(hash.prefix(32)) + ".png"
        if let idx = items.firstIndex(where: { $0.imageFile == name }) {
            var existing = items.remove(at: idx)
            existing.date = Date()
            items.insert(existing, at: 0)
        } else {
            do { try png.write(to: imagesDir.appendingPathComponent(name), options: .atomic) } catch { return }
            let label = L("Image %d×%d", Int(size.width), Int(size.height))
            items.insert(ClipItem(text: label, imageFile: name), at: 0)
        }
        trimAndSave()
    }

    private func trimAndSave() {
        var count = 0
        var removed: [ClipItem] = []
        items = items.filter { item in
            if item.favorite { return true }
            count += 1
            if count <= maxHistory { return true }
            removed.append(item)
            return false
        }
        removed.forEach(deleteImageFile)
        save()
    }

    // MARK: - Actions

    /// Puts the item on the pasteboard without recording it again as a new entry.
    /// - Parameter plain: text only, dropping the original formatting.
    func copy(_ item: ClipItem, plain: Bool = false) {
        let pb = pasteboard
        pb.clearContents()
        if let file = item.imageFile {
            guard let data = try? Data(contentsOf: imagesDir.appendingPathComponent(file)) else { return }
            pb.setData(data, forType: .png)
            if let tiff = NSImage(data: data)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
        } else {
            pb.setString(item.text, forType: .string)
            if !plain {
                if let rtf = item.rtf { pb.setData(rtf, forType: .rtf) }
                if let html = item.html { pb.setData(html, forType: .html) }
            }
        }
        lastChangeCount = pb.changeCount

        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: idx)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func toggleFavorite(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[idx].favorite.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteImageFile(item)
        save()
    }

    func clearHistory() {
        let removed = items.filter { !$0.favorite }
        items.removeAll { !$0.favorite }
        removed.forEach(deleteImageFile)
        save()
    }

    // MARK: - Images

    func image(for item: ClipItem) -> NSImage? {
        guard let file = item.imageFile else { return nil }
        if let cached = thumbCache.object(forKey: file as NSString) { return cached }
        guard let img = NSImage(contentsOf: imagesDir.appendingPathComponent(file)) else { return nil }
        thumbCache.setObject(img, forKey: file as NSString)
        return img
    }

    private func deleteImageFile(_ item: ClipItem) {
        guard let file = item.imageFile, !items.contains(where: { $0.imageFile == file }) else { return }
        try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(file))
        thumbCache.removeObject(forKey: file as NSString)
    }

    // MARK: - Persistence

    private func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: fileURL, options: .atomic)
    }
}

/// Panel UI state (search and selection), shared by the view and the keyboard handler.
final class PanelState: ObservableObject {
    @Published var search = ""
    @Published var selected = 0
    @Published var openCount = 0   // bumped every time the panel opens
}
